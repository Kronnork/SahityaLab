"""Structured manuscript outlines for common literature-review designs."""
from __future__ import annotations

from typing import Any


COMMON_DECLARATIONS = """## Declarations

### Funding
[Report funding and the role of the funder.]

### Competing interests
[Declare competing interests.]

### Data and materials availability
[State where search strategies, screening data, extraction tables and analysis files can be accessed.]

### Author contributions
[Describe contributions according to the journal's required taxonomy.]
"""


def review_manuscript_outline(title: str, review_type: str = "systematic_literature_review") -> str:
    """Return an editable outline; headings are prompts, not a completed paper."""
    kind = review_type.casefold().replace("-", "_").replace(" ", "_")
    title_block = f"# {title}\n\n> Working outline generated by SāhityaLab. Replace prompts with verified methods, evidence and interpretation.\n"
    abstract = """## Abstract

### Purpose
[State the problem and review objective.]

### Design/methodology/approach
[Describe review design, sources, search dates, eligibility, selection and synthesis.]

### Findings
[Report the verified number and characteristics of included studies and the main synthesis findings.]

### Originality/value
[State the contribution of this review.]

### Keywords
[Add controlled and author keywords.]
"""
    if kind in {"scoping_review", "scoping"}:
        methods = """## Methodology

### Review framework and questions
[Specify the scoping-review framework and questions.]

### Eligibility criteria
[Define population/concept/context or other applicable framework.]

### Information sources and search strategy
[List databases, platforms, dates, full search strings and limits.]

### Selection of sources of evidence
[Describe duplicate handling, independent screening and conflict resolution.]

### Data charting
[Describe the charting form, pilot process and variables.]

### Collation, summary and reporting
[Explain how evidence was mapped and presented.]
"""
    elif kind in {"integrative_review", "integrative"}:
        methods = """## Methodology

### Review design and rationale
[Explain the integrative review design and synthesis logic.]

### Problem formulation and research questions
[Define the question and concepts.]

### Literature search and source selection
[Report sources, search strings, dates, eligibility and selection.]

### Data evaluation and extraction
[Describe critical appraisal, extraction and quality considerations.]

### Data analysis and synthesis
[Explain how diverse evidence was compared and integrated.]
"""
    elif kind in {"narrative_review", "narrative"}:
        methods = """## Review approach

### Scope and review questions
[Define the scope and the rationale for the selected literature.]

### Search and selection approach
[Describe information sources, search concepts, date ranges and selection logic.]

### Critical assessment and synthesis
[Explain how sources were evaluated, compared and synthesised.]
"""
    else:
        methods = """## Methodology

### Review protocol and research questions
[State the protocol, objectives and research questions.]

### Eligibility criteria
[Specify inclusion/exclusion criteria, population/context, publication type and date/language boundaries.]

### Information sources and search strategy
[List databases, platforms, coverage dates, exact search strings, filters and search dates.]

### Selection process
[Describe deduplication, reviewer roles, screening stages, conflict resolution and full-text exclusion reasons.]

### Data collection and extraction
[Describe the extraction form, pilot process, variables and how missing data were handled.]

### Quality or risk-of-bias assessment
[Name the appraisal approach and explain reviewer procedures.]

### Synthesis methods
[Explain how studies were grouped, compared and synthesised; distinguish descriptive mapping from interpretive synthesis.]
"""
    results = """## Results

### Study selection
[Report the record counts at each stage and include a PRISMA flow diagram where applicable.]

### Characteristics of included studies
[Summarise years, sources, contexts, methods, theories and other extracted characteristics.]

### Bibliometric or descriptive landscape
[Report only indicators that answer the review questions. Explain data coverage and limitations.]

### Thematic or analytical synthesis
[Present each theme with a definition, supporting studies, convergent/divergent evidence and critical interpretation.]

### Evidence gaps
[Identify well-supported gaps and distinguish them from gaps caused by search or data limitations.]
"""
    discussion = """## Discussion

### Principal findings
[Answer each research question using the synthesised evidence.]

### Theoretical implications
[Explain how the synthesis confirms, extends, challenges or contextualises existing theory.]

### Practical and policy implications
[State implications supported by the evidence and define their boundary conditions.]

### Limitations
[Discuss search, database coverage, language, selection, extraction, appraisal and synthesis limitations.]

### Future research
[Derive specific research directions from identified evidence gaps.]

## Conclusion
[Provide a concise answer to the review objective, contribution and boundary conditions.]
"""
    return "\n".join([title_block, abstract, "## Introduction\n\n### Background and rationale\n[Establish the problem and explain why this review is needed.]\n\n### Review objective and research questions\n[State the objective and each research question.]\n", methods, results, discussion, COMMON_DECLARATIONS])


def extraction_fields(protocol: dict[str, Any] | None = None) -> list[str]:
    configured = (protocol or {}).get("extraction_fields")
    return list(configured) if configured else [
        "title", "authors", "year", "journal", "doi", "research_question",
        "theory", "methodology", "context", "sample", "key_findings",
        "limitations", "future_research", "reviewer_notes",
    ]
